#!/usr/bin/env bash
#
# lib/install/stage-03-mirror.sh - stage 3: mirror selection and keyring refresh.
#
# Implements Plan-Main.md section 3 - mirror selection and keyring refresh
# (source lines 180-198):
#   * ask whether to replace the pacman mirrorlist, offering four choices
#   * 1) reflector (recommended): ask for a country, write it to $COUNTRY,
#        install reflector if missing, back up the current mirrorlist, run
#        reflector into a temporary file and only install it after validating
#        that the result is non-empty and contains "Server =" lines
#   * 2) use dependence/mirrorlist, falling back to an embedded mirror list
#   * 3) manual configuration: print the path and a USTC example, then exit
#   * 4) skip, keep the Live ISO mirrorlist untouched
#   * every path ends with "pacman -Syy --noconfirm archlinux-keyring"
#
# Runtime text is pure ASCII (Plan-Main.md appendix C: the TTY has no CJK
# fonts).  errexit / nounset / pipefail are already enabled by the entry
# point Arch-Auto-Install.sh; this module is sourced, never executed.

# Embedded fallback mirrorlist.  Only used when dependence/mirrorlist is
# missing and the user picked option 2.
AIT_FALLBACK_MIRRORLIST=$'## Arch Linux repository mirrorlist (embedded fallback)\n## Generated by Arch-Auto-Install stage 3.\n\nServer = https://mirrors.ustc.edu.cn/archlinux/$repo/os/$arch\nServer = https://mirrors.tuna.tsinghua.edu.cn/archlinux/$repo/os/$arch\nServer = https://mirrors.aliyun.com/archlinux/$repo/os/$arch\nServer = https://mirrors.huaweicloud.com/archlinux/$repo/os/$arch\n'

AIT_MIRRORLIST='/etc/pacman.d/mirrorlist'
AIT_MIRRORLIST_BAK_PREFIX='/etc/pacman.d/mirrorlist.bak.'

# _mirror_trim <string>
# Strips leading and trailing blanks, prints the result on stdout.
_mirror_trim() {
    local value="$1"
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    printf '%s' "$value"
}

# _mirror_ask_country
# Asks for an English country name, an ISO code or a comma separated list
# ("China", "cn", "cn,jp").  Empty or blank-only input falls back to cn.
# Input longer than 40 characters is rejected and asked again.
# The accepted value is written to the global COUNTRY.
_mirror_ask_country() {
    local raw=''
    local value=''

    while :; do
        raw=$(read_answer 'Countries for reflector (name or ISO code, comma separated) [cn]: ' 'cn')
        value=$(_mirror_trim "$raw")
        if [[ -z $value ]]; then
            value='cn'
        fi
        if [[ ${#value} -gt 40 ]]; then
            log_warn "Country string is ${#value} characters long; the limit is 40. Please retry."
            continue
        fi
        COUNTRY="$value"
        return 0
    done
}

# _mirror_ask_choice
# Prints the four-option menu and returns the validated choice on stdout.
_mirror_ask_choice() {
    local choice=''

    while :; do
        {
            printf '\n'
            printf 'How do you want to configure %s?\n' "$AIT_MIRRORLIST"
            printf '  1) reflector - search the fastest mirrors automatically [RECOMMENDED]\n'
            printf '  2) use the mirror list shipped with this repository\n'
            printf '  3) manual configuration (not recommended for beginners)\n'
            printf '  4) skip, keep the current mirrorlist\n'
        } >/dev/tty

        choice=$(read_answer 'Your choice [1-4]: ' '1')
        choice="${choice//[[:space:]]/}"
        case $choice in
            1 | 2 | 3 | 4)
                printf '%s' "$choice"
                return 0
                ;;
            *)
                log_warn "Invalid choice '${choice}'. Please enter 1, 2, 3 or 4."
                ;;
        esac
    done
}

# _mirror_reflector
# Option 1: generate a mirrorlist with reflector.
_mirror_reflector() {
    local backup=''
    local tmp=''

    _mirror_ask_country
    log_info "Countries selected for reflector: ${COUNTRY}"

    if ! command -v reflector >/dev/null 2>&1; then
        log_info 'reflector is not installed; installing it now.'
        pacman -Sy --needed --noconfirm reflector || die 'Failed to install reflector.'
    fi

    backup="${AIT_MIRRORLIST_BAK_PREFIX}$(date +%Y%m%d-%H%M%S)"
    if [[ -f $AIT_MIRRORLIST ]]; then
        cp -a "$AIT_MIRRORLIST" "$backup" || die "Failed to back up ${AIT_MIRRORLIST}."
        log_ok "Current mirrorlist backed up to ${backup}"
    fi

    tmp=$(mktemp "${TMPDIR:-/tmp}/ait-mirrorlist.XXXXXX") || die 'Failed to create a temporary file.'

    log_info 'Running reflector (age 48h, 10 mirrors, sorted by score, https only).'
    if ! reflector -a 48 -c "$COUNTRY" -f 10 --sort score --verbose -p https --save "$tmp"; then
        rm -f "$tmp"
        die 'reflector failed; the mirrorlist was left untouched.'
    fi

    # reflector exits 0 even when it found no mirror, and in that case writes
    # no file at all.  Without this check "--save" would look like a success
    # while the old (slow) mirrorlist is still in place.
    if [[ ! -s $tmp ]] || ! grep -q '^Server =' "$tmp"; then
        rm -f "$tmp"
        die 'reflector produced no usable mirrors; the mirrorlist was left untouched.'
    fi

    install -m 644 "$tmp" "$AIT_MIRRORLIST" || {
        rm -f "$tmp"
        die "Failed to install the generated mirrorlist to ${AIT_MIRRORLIST}."
    }
    rm -f "$tmp"
    log_ok "Package mirrorlist replaced from reflector results (backup: ${backup})."
}

# _mirror_repo_list
# Option 2: install dependence/mirrorlist, or the embedded fallback list.
_mirror_repo_list() {
    local src="${AIT_ROOT:-}/dependence/mirrorlist"

    if [[ -n ${AIT_ROOT:-} && -r $src ]]; then
        install -m 644 "$src" "$AIT_MIRRORLIST" || die "Failed to install ${src} to ${AIT_MIRRORLIST}."
        log_ok "Package mirrorlist installed from ${src}."
        return 0
    fi

    log_warn 'dependence/mirrorlist is missing; using the built-in fallback mirror list.'
    printf '%s' "$AIT_FALLBACK_MIRRORLIST" >"$AIT_MIRRORLIST" \
        || die "Failed to write ${AIT_MIRRORLIST}."
    chmod 644 "$AIT_MIRRORLIST" || die "Failed to chmod ${AIT_MIRRORLIST}."
    log_ok "Package mirrorlist written from the built-in fallback list."
}

# _mirror_manual
# Option 3: explain how to do it by hand, then stop the installer.
_mirror_manual() {
    log_info 'Manual mirror configuration selected.'
    log_info "Edit the file: ${AIT_MIRRORLIST}"
    log_info 'Keep one "Server =" line per mirror, then save and exit your editor.'
    log_info 'Example line (USTC, China):'
    # shellcheck disable=SC2016  # $repo and $arch must stay literal placeholders
    printf '%s\n' '  Server = https://mirrors.ustc.edu.cn/archlinux/$repo/os/$arch' >/dev/tty
    log_warn 'Manual setup is NOT recommended for users without Arch Linux experience.'
    log_info 'Nothing was changed. Re-run this installer once the mirrorlist is ready.'
    die 'Exiting for manual mirror configuration.'
}

# stage_03_mirror - Plan-Main.md stage 3 entry point (no arguments).
stage_03_mirror() {
    local choice=''

    : "${COUNTRY:=cn}"
    printf '\n'
    log_info 'Stage 3: package mirror selection and keyring refresh'

    choice=$(_mirror_ask_choice)

    case $choice in
        1) _mirror_reflector ;;
        2) _mirror_repo_list ;;
        3) _mirror_manual ;;
        4) log_warn 'Mirror configuration skipped; the current mirrorlist is kept.' ;;
    esac

    log_info 'Refreshing package databases and installing archlinux-keyring.'
    pacman -Syy --noconfirm archlinux-keyring || die 'Failed to refresh databases or install archlinux-keyring.'
    log_ok 'Package databases refreshed and keyring updated.'
}
